const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const read=relative=>fs.readFileSync(path.join(root,relative),'utf8');
const assert=(condition,message)=>{if(!condition)throw new Error(message)};

const migration=read('src/database/migrations/20260928_backup_verification_runs.sql');
const common=read('scripts/backup-common.js');
const dump=read('scripts/database-backup.js');
const restore=read('scripts/verify-database-backup.js');
const storage=read('scripts/backup-private-storage.js');
const r2Backup=read('src/services/privateStorageBackupScheduler.js');
const server=read('src/server.js');
const worker=read('src/worker.js');
const health=read('src/services/adminSystemHealthService.js');
const healthPage=read('../frontend/src/admin/pages/AdminSystemHealth.jsx');
const packageJson=read('package.json');
const workflow=read('../.github/workflows/ci.yml');
const gitignore=read('../.gitignore');

assert(migration.includes('CREATE TABLE IF NOT EXISTS backup_verification_runs'),'Backup verification history table is missing');
assert(common.includes('pg_export_snapshot')===false,'Snapshot export must remain owned by the database-backup operation');
assert(common.includes('ensureBackupVerificationSchema'),'Backup verification must preflight its schema before expensive backup work');
assert(common.includes('BACKUP_SCHEMA_NOT_READY')&&common.includes('npm run db:migrate'),'Missing backup schema must produce an actionable migration error');
assert(dump.includes('pg_export_snapshot()'),'Database backup must export a PostgreSQL snapshot');
assert(dump.includes("'--snapshot',snapshot"),'pg_dump must use the exact exported snapshot used for source metrics');
assert(dump.includes("'--format=custom'")&&dump.includes("'--no-owner'")&&dump.includes("'--no-privileges'"),'Database dump must be portable and not restore owners/privileges');
assert(restore.includes("propulse_restore_verify_"),'Restore verification must use the protected temporary database prefix');
assert(restore.includes('await ensureBackupVerificationSchema()'),'Database restore verification must check schema before creating a dump');
assert(restore.includes('compareMetrics'),'Restore verification must compare exact source/restored metrics');
assert(restore.includes('DROP DATABASE')&&restore.includes('WITH (FORCE)'),'Restore verification must always target and clean up a disposable database');
assert(storage.includes('isSymbolicLink()'),'Private-storage backups must reject symbolic links');
assert(storage.includes('await ensureBackupVerificationSchema()'),'Private-storage verification must check schema before copying files');
assert(storage.includes('verifySnapshot'),'Private-storage backups must verify copied file hashes');
assert(storage.includes('PRIVATE_STORAGE_BACKUP_DIRECTORY must not be inside UPLOAD_STORAGE_ROOT'),'Storage backup destination must not recurse into live uploads');
assert(storage.includes('runPrivateStorageBackupCore({force:true})'),'R2 backup command must copy and verify real objects instead of only probing the primary bucket');
assert(r2Backup.includes("backupBucket")&&r2Backup.includes("snapshots/")&&r2Backup.includes('s3.headObject'),'Automated R2 backup must target protected snapshot paths and verify each copied object');
assert(r2Backup.includes('chooseBackupTarget')&&r2Backup.includes("locked_primary_prefix"),'Automated R2 backup must remain available when production credentials are bucket-scoped');
assert(r2Backup.includes('backup_verification_runs')&&r2Backup.includes("status:'verified'"),'Automated R2 backup must persist verified backup state');
assert(r2Backup.includes('restoredManifest')&&r2Backup.includes('sha256(restoredManifest.buffer)'),'Backup manifest verification must fall back to readback checksum verification when HEAD metadata differs');
assert(server.includes('startPrivateStorageBackupScheduler')&&worker.includes('startPrivateStorageBackupScheduler'),'R2 backups must run in both supported background-job deployment modes');
assert(packageJson.includes('"backup:verify"')&&packageJson.includes('"backup:storage"')&&packageJson.includes('"backup:all"'),'Operator backup commands must be exposed in package scripts');
assert(workflow.includes('Verify database backup restore drill'),'CI must execute a real database dump/restore drill');
assert(workflow.includes('Verify private upload storage backup'),'CI must execute a private-storage backup verification');
assert(gitignore.includes('/backups/'),'Generated backups must never be committed');
assert(health.includes('backupVerificationService.getHealthSummary'),'System Health must read persisted backup verification state');
assert(healthPage.includes('Backup verification'),'System Health UI must expose backup verification');
console.log('Backup and restore automation regression test passed.');
