const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const {recordMatches}=require('../src/services/professionalRequestAccessService');
const source='professional_project_quote';
const lead={source,custom_fields:{_project_origin:{type:'quote',requestId:81,professionalUserId:120}}};
assert.equal(recordMatches(lead,'quote',81,120),true);
assert.equal(recordMatches(lead,'quote',81,999),false,'A different professional cannot unlock the enquiry');
assert.equal(recordMatches(lead,'callback',81,120),false,'A callback ID must never match quote ownership');
assert.equal(recordMatches(lead,'quote',82,120),false,'A different quote ID cannot be unlocked');
assert.equal(recordMatches({...lead,source:'manual'},'quote',81,120),false,'User cannot unlock arbitrary leads');
assert.equal(recordMatches({source:'professional_profile_callback',custom_fields:{_project_origin:{type:'profile',requestId:90,professionalUserId:120}}},'profile',90,120),true);
