const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=file=>fs.readFileSync(path.join(root,file),'utf8')

const profile=read('frontend/src/pages/Profile.jsx')
const brochures=read('frontend/src/pages/ProfessionalBrochures.jsx')
const compact=read('frontend/src/pages/ProfileCompact.css')
const workspace=read('frontend/src/pages/ProfileWorkspace.css')
const routes=read('frontend/src/App.jsx')
const profileService=read('backend/src/services/profileService.js')
const profileController=read('backend/src/controllers/profileController.js')

// One accordion and one professional package studio, without old duplicated
// private/public profile tabs or an independent add-package workflow.
assert.match(profile,/openProfileCard/)
assert.match(profile,/toggleCard/)
assert.match(profile,/packageView==='brochures'/)
assert.match(profile,/ProfessionalBrochures embedded/)
assert.match(profile,/onClick=\{addProject\}>\+ Add Project/)
assert.doesNotMatch(profile,/onClick=\{addPlan\}>\+ Add Package/)
assert.match(profile,/expandedProject===projectKey\(project\)/)
assert.match(profile,/expandedPlan===planKey\(plan\)/)
assert.match(profile,/aria-expanded=\{isExpanded\}/)
assert.match(profile,/revealProjectError/)
assert.match(profile,/revealPlanError/)
assert.match(profile,/profile-unified-visibility/)
assert.match(profile,/Public expert listing/)
assert.match(profile,/Company Brochures/)
assert.match(profile,/ProfessionalPackageSpecEditor/)
assert.match(profile,/specSections:.*spec_sections/)
assert.match(profile,/profile-accordion-savebar/)
assert.match(profile,/card\.id==='proofs'/)
assert.doesNotMatch(profile,/activeSection==='public'/)
assert.doesNotMatch(profile,/activeSection==='business'/)
assert.equal((profile.match(/<ProfileBusinessFields /g)||[]).length,1)

// Existing brochure functionality must still work inside the unified panel.
assert.match(brochures,/embedded=false/)
assert.match(brochures,/onClick=\{addBrochure\}/)
assert.match(brochures,/method:'PUT'/)
assert.match(brochures,/Preview document/)
assert.match(brochures,/setExpanded\(null\)/)
assert.match(routes,/path="\/profile\/brochures" element=\{<Navigate to="\/profile\?tab=brochures" replace\/>\}/)
assert.match(compact,/@media\(max-width:620px\)/)
assert.match(workspace,/profile-accordion/)

// Business and public listing share only one stored business profile.
assert.match(profileService,/String\(businessName\|\|''\)\.trim\(\)\.slice\(0,180\)/)
assert.match(profileService,/String\(businessDetails\|\|''\)\.trim\(\)\.slice\(0,3000\)/)
assert.match(profileService,/public_headline=\$4,public_summary=\$5/)
assert(!profileController.includes('publicHeadline,publicSummary'),'Duplicate public text fields must not return')
console.log('Unified professional profile accordion, specification editor and brochure regression checks passed.')
