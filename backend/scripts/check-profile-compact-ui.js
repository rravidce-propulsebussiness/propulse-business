const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const root=path.resolve(__dirname,'../..')
const read=file=>fs.readFileSync(path.join(root,file),'utf8')

const profile=read('frontend/src/pages/Profile.jsx')
const brochures=read('frontend/src/pages/ProfessionalBrochures.jsx')
const style=read('frontend/src/pages/ProfileCompact.css')
const routes=read('frontend/src/App.jsx')

assert.match(profile,/activeSection==='brochures'\?<ProfessionalBrochures embedded\/>/)
assert.match(profile,/onClick=\{addProject\}>\+ Add Project/)
assert.match(profile,/onClick=\{addPlan\}>\+ Add Package/)
assert.match(profile,/expandedProject===projectKey\(project\)/)
assert.match(profile,/expandedPlan===planKey\(plan\)/)
assert.match(profile,/aria-expanded=\{isExpanded\}/)
assert.match(profile,/profile-form-wide/)
assert.match(profile,/revealProjectError/)
assert.match(profile,/revealPlanError/)
assert.match(brochures,/embedded=false/)
assert.match(brochures,/onClick=\{addBrochure\}/)
assert.match(brochures,/method:'PUT'/)
assert.match(brochures,/Preview document/)
assert.match(brochures,/setExpanded\(null\)/)
assert.match(routes,/path="\/profile\/brochures" element=\{<Navigate to="\/profile\?tab=brochures" replace\/>\}/)
assert.match(style,/\.profile-form-wide>\.profile-side-column\{display:none\}/)
assert.match(style,/@media\(max-width:620px\)/)
assert(profile.indexOf('<div className="profile-save">')<profile.indexOf('<aside className="profile-side-column">'))
console.log('Compact professional profile, company brochures, responsive layout and navigation checks passed.')
