import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const app=read('src/App.jsx')
const nav=read('src/components/UserHeader.jsx')
const customerFaq=read('src/pages/UserFAQ.jsx')
const proFaq=read('src/pages/ProfessionalFAQ.jsx')
const faqShared=read('src/components/WebsiteFaqSection.jsx')
const roadmap=read('src/pages/UpcomingFeatures.jsx')
const admin=read('src/admin/pages/AdminUpcomingFeatures.jsx')
const server=read('../backend/src/server.js')
const faqBackend=read('../backend/src/services/faqService.js')
const faqAdmin=read('src/admin/pages/AdminFaqs.jsx')
const faqMigration=read('../backend/src/database/migrations/20261026_professional_faq_audience.sql')
const backend=read('../backend/src/services/upcomingFeatureService.js')
const controller=read('../backend/src/controllers/upcomingFeatureController.js')
const migration=read('../backend/src/database/migrations/20261026_professional_roadmap_audiences.sql')

assert(app.includes('<Route path="/faq" element={<UserFAQ/>}/>'),'Homeowner FAQ must remain unchanged')
assert(app.includes('<Route path="/professional-faq" element={<ProfessionalFAQ/>}/>'),'Professional FAQ must be separate')
assert(app.includes('<Route path="/upcoming-features" element={<UpcomingFeatures audience="homeowner"/>}/>'),'Homeowner roadmap must be separate')
assert(app.includes('<Route path="/professional-upcoming-features" element={<UpcomingFeatures audience="professional"/>}/>'),'Professional roadmap must be separate')
assert(nav.includes('to="/professional-faq"')&&nav.includes('to="/professional-upcoming-features"'),'Professional menu must link to professional pages')
assert(!nav.includes('to="/faq"')&&!nav.includes('to="/upcoming-features"'),'Professional menu must not link to homeowner pages')
assert(customerFaq.includes('audience="homeowner"'),'Homeowner FAQ audience must remain homeowner')
assert(proFaq.includes('audience="professional"')&&proFaq.includes('<UserHeader/>'),'Professional FAQ must use its own audience and business header')
assert(faqShared.includes("professional=audience==='professional'"),'Shared FAQ should support professional audience')
assert(faqShared.includes("audience='homeowner'"),'Unspecified FAQ audiences must not default to professionals')
assert(faqAdmin.includes("['professional','Professional / Business FAQs'"),'Admin FAQ editor must target professional content independently')
assert(faqBackend.includes("'homeowner','professional','website'"),'FAQ API must recognize both new and legacy professional audiences')
assert(faqMigration.includes("SET audience='professional' WHERE audience='website'"),'Old business FAQs must migrate to the professional audience')
assert(server.includes('|professional-faq|professional-upcoming-features|professional-requests|'),'Backend SPA fallback must serve professional help, roadmap and requests on direct navigation')
assert(faqShared.includes('to="/professional-contact"')&&faqShared.includes('to="/quote"'),'FAQ support links must remain audience-specific')
assert(roadmap.includes("publicRequest('/upcoming-features?audience='+encodeURIComponent(audience))"),'Roadmap API must request the selected audience')
assert(roadmap.includes('professional?<UserHeader/>:<PublicHeader/>'),'Roadmap headers must be audience-specific')
assert(roadmap.includes('professional?<footer')&&roadmap.includes('<PublicFooter />'),'Roadmap footer must be audience-specific')
assert(admin.includes("audience==='professional'")&&admin.includes("audience==='homeowner'"),'Admin roadmap must show both audiences')
assert(admin.includes('value={form.audience}'),'Admin feature editor must select the audience')
assert(backend.includes("conditions.push('audience=$'+values.length)"),'Public roadmap must filter by audience in SQL')
assert(backend.includes('const where=conditions.length')&&backend.includes('values\n  );'),'Roadmap SQL must use parameterized values')
assert(backend.includes('audience:audienceFrom(input.audience)'),'Roadmap writes must validate audience')
assert(controller.includes("req.query?.audience||'homeowner'"),'Public roadmap must default to homeowners')
assert(migration.includes("DEFAULT 'professional'")&&migration.includes("('homeowner','professional')"),'Existing business features must remain professional')
console.log('Professional vs homeowner navigation and content regression passed.')
